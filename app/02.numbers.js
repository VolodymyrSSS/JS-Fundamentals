/*
  Створіть програму, яка керуватиме роботою касового апарату. Ви отримаєте
  три квитанції на вході, кожна з яких містить суму (ціле число) та літеру
  як відповідний відсоток податку (ціле число), щоб обчислити, яка частина
  сплаченої суми становить податок. Напишіть програму, яка зчитує 4 квитанції
  зі стандартного вводу, спочатку вводячи число, а потім символ.
    A - 18% податку
    B - 10% податку
    C - 7% податку
  Виведіть загальну суму сплаченого податку
    Вхід:
      10000 A
      7500 B
      18000 C
      11500 B
  Вихід: Total VAT paid: 4960
*/
// Solution:
// Підключаємо модуль fs для читання вводу
// const fs = require("fs");
// Зчитуємо весь ввід як рядок і розділяємо його по рядках
// const input = fs.readFileSync(0, "utf8").trim().split("\n");

const input5 = ["10000 A", "7500 B", "18000 C", "11500 B"]; // Зчитуємо 4 квитанції зі стандартного вводу

// Створюємо об’єкт зі ставками податку для кожного типу квитанції
const taxRates = {
  A: 18, // тип A → 18%
  B: 10, // тип B → 10%
  C: 7, // тип C → 7%
};

// Змінна для накопичення загальної суми ПДВ
let totalTax = 0;

// Перебираємо кожен рядок вводу (кожна квитанція)
for (let line of input5) {
  // Розділяємо рядок на суму та тип квитанції (через пробіл) деструктуризацією масиву
  const [amountStr, type] = line.trim().split(" ");

  // Перетворюємо суму з рядка у число
  const amount = Number(amountStr);

  // Знаходимо ставку податку за типом квитанції
  const taxRate = taxRates[type];

  // Обчислюємо податок: сума × ставка / 100
  const tax = (amount * taxRate) / 100;

  // Додаємо цей податок до загальної суми
  totalTax += tax;
}

// Виводимо результат у потрібному форматі
console.log(`Total VAT paid: ${totalTax}`); // Output: Total VAT paid: 4960

