let matrix = [];

// 1-й цикл: зчитуємо кожен рядок матриці та перетворюємо у числа
for (let i = 1; i <= N; i++) {
  matrix.push(input[i].split(" ").map(Number));
}

// 2-й цикл: проходимо по всіх елементах матриці
for (let i = 0; i < N; i++) {
  for (let j = 0; j < N; j++) {
    // Якщо елемент знаходиться на або під головною діагоналлю
    if (i >= j) {
      // Міняємо знак числа (позитив → негатив, негатив → позитив)
      matrix[i][j] = -matrix[i][j];
    }
  }
}
