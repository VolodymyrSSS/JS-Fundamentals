/*
  Створіть функцію з назвою kth_smallest, яка отримує масив різних елементів,
  довжину масиву (n) та ціле число k (k <=n). Повертає k-й найменший елемент
  масиву. Приклад: arr=[2,4,6,1,5,7,8], n=7, k=3 то третій найменший елемент
  буде мати значення 4.
*/
/* Алгоритм рішення:
  1. Сортуємо масив у зростаючому порядку;
  2. Після сортування найменший елемент буде першим, другий найменший — другим і так далі.
     Тому k‑й найменший елемент буде на позиції k-1.
  3. Повертаємо елемент на позиції k-1.
*/
function kth_smallest(arr, n, k) {
  // Сортуємо масив у зростаючому порядку
  arr.sort((a, b) => a - b);

  // Повертаємо k-й найменший елемент (індекс k-1)
  return arr[k - 1];
}
kth_smallest([2, 4, 6, 1, 5, 7, 8], 7, 3); // 4
