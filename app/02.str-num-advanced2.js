// Функція злиття двох відсортованих частин масиву
function merge(arr, temp, left, mid, right) {
  let invCount = 0; // лічильник інверсій
  let i = left, // індекс для лівої частини
    j = mid, // індекс для правої частини
    k = left; // індекс для тимчасового масиву

  // Порівнюємо елементи з обох частин
  while (i <= mid - 1 && j <= right) {
    if (arr[i] <= arr[j]) {
      temp[k++] = arr[i++]; // якщо лівий елемент менший — копіюємо його
    } else {
      temp[k++] = arr[j++]; // якщо правий елемент менший — копіюємо його
      invCount += mid - i; // додаємо кількість інверсій (скільки лишилось у лівій частині)
    }
  }

  // Додаємо залишки з лівої частини
  while (i <= mid - 1) temp[k++] = arr[i++];

  // Додаємо залишки з правої частини
  while (j <= right) temp[k++] = arr[j++];

  // Копіюємо тимчасовий масив назад у основний
  for (let x = left; x <= right; x++) arr[x] = temp[x];

  return invCount; // повертаємо кількість інверсій
}

// Рекурсивна функція merge sort із підрахунком інверсій
function mergeSort(arr, temp, left, right) {
  let invCount = 0;
  if (right > left) {
    const mid = Math.floor((right + left) / 2); // знаходимо середину

    // Рекурсивно сортуємо ліву частину
    invCount += mergeSort(arr, temp, left, mid);

    // Рекурсивно сортуємо праву частину
    invCount += mergeSort(arr, temp, mid + 1, right);

    // Зливаємо дві частини та додаємо інверсії
    invCount += merge(arr, temp, left, mid + 1, right);
  }
  return invCount;
}

// Основна функція для підрахунку суміжних перестановок
function countSwaps(arr, n) {
  const temp = new Array(n).fill(0); // тимчасовий масив для злиття
  return mergeSort(arr, temp, 0, n - 1);
}

