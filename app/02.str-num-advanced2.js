function swap_list2(arr) {
  // Проходимо по масиву один раз
  for (let i = 0; i < arr.length - 1; i++) {
    // Якщо поточний елемент більший за наступний — міняємо місцями
    if (arr[i] > arr[i + 1]) {
      let temp = arr[i];
      arr[i] = arr[i + 1];
      arr[i + 1] = temp;
    }
  }
  return arr; // Повертаємо масив після одного проходу
}
