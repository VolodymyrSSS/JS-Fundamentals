/*
    Створіть функцію bubble_sort, яка отримує масив та його розмір. Переберіть масив,
    порівняйте та поміняйте місцями сусідні елементи. Повторіть цей процес n разів, щоб
    отримати остаточний відсортований список. Поверніть відсортований список.
*/
// Solution:
/* Тепер ми переходимо від одного проходу до повного алгоритму Bubble Sort. Як зазначено,
    для масиву з n елементів потрібно зробити n проходів, щоб гарантовано відсортувати
    список. Отже, алгоритм Bubble Sort:
   1. Повторюємо процес n разів.
   2. На кожному проході йдемо по масиву від початку до кінця.
   3. Якщо сусідні елементи не в порядку (arr[j] > arr[j+1]), міняємо їх місцями.
   4. Після кожного проходу найбільший елемент «спливає» в кінець.
   5. Після n проходів масив гарантовано відсортований.
*/
function bubble_sort(arr, n) {
  // Зовнішній цикл — кількість проходів, який гарантує, що ми зробимо достатньо проходів.
  for (let i = 0; i < n; i++) {
    // Внутрішній цикл — порівняння сусідніх елементів
    for (let j = 0; j < n - 1; j++) {
      if (arr[j] > arr[j + 1]) {
        // Міняємо місцями
        let temp = arr[j];
        arr[j] = arr[j + 1];
        arr[j + 1] = temp;
      }
    }
  }
  return arr;
}
