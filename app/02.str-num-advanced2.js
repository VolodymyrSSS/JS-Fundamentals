const N13 = 10; // визначаєм число N

// допоміжна функція для обчислення суми дільників числа x
function sumOfDivisors(x) {
  let sum = 0; // лічильник суми

  // перебираємо всі числа від 1 до x
  for (let i = 1; i <= x; i++) {
    // якщо i є дільником x
    if (x % i === 0) {
      sum += i; // додаємо його до суми
    }
  }
  return sum; // повертаємо суму дільників
}

