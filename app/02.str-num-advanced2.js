/*
  Різниця між мінімальним та максимальним елементами масиву.
  Створіть функцію з назвою min_max, яка отримує масив та його розмір. Виведіть різницю
  між максимальним та мінімальним елементами масиву. Приклад вхідних даних: [3,2,5,3,6]
  Максимальна кількість елементів дорівнює 6, мінімальна кількість елементів дорівнює 2.
  Різниця дорівнює 6 - 2 = 4 Вихідні дані: 4
*/
// Solution:
/* Алгоритм вирішення буде:
  1.Припускаємо, що перший елемент — і мінімум, і максимум.
  2.Ітеруємо масив:
    - якщо знайдемо менший → оновлюємо min;
    - якщо знайдемо більший → оновлюємо max.
  3.Повертаємо різницю max - min.
*/
function min_max(arr, n) {
  // Початкові значення
  let min = arr[0];
  let max = arr[0];

  // Проходимо по масиву
  for (let i = 1; i < n; i++) {
    if (arr[i] < min) {
      min = arr[i]; // оновлюємо мінімум
    }
    if (arr[i] > max) {
      max = arr[i]; // оновлюємо максимум
    }
  }

  // Повертаємо різницю
  return max - min;
}
