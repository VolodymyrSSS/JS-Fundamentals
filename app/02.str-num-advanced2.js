/* Ми можемо побудувати послідовність поступово, але не через вкладені 
  цикли — а через накопичення рядка. Це дає точний контроль над цифрами.
  */
function digit2(n) {
  n = Number(n);
  let seq = "";
  let i = 1;

  while (seq.length < n) {
    for (let j = 1; j <= i; j++) {
      seq += j;
    }
    i++;
  }

  return Number(seq[n - 1]);
}
