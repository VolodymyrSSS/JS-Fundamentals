// Допоміжна функція: шукає найбільше число, що ділиться на 3, змінюючи лише одну цифру
function largestNum(n) {
  const digits = n.toString().split("").map(Number); // розбиваємо число на цифри
  let best = -1; // зберігаємо найкращий кандидат

  // Перебираємо кожну позицію
  for (let i = 0; i < digits.length; i++) {
    // Пробуємо замінити цифру на всі можливі від 0 до 9
    for (let d = 0; d <= 9; d++) {
      if (d === digits[i]) continue; // пропускаємо, якщо цифра не змінюється

      const newDigits = [...digits]; // копія масиву цифр
      newDigits[i] = d; // замінюємо цифру на позиції i
      const candidate = parseInt(newDigits.join(""), 10); // формуємо нове число

      // Перевіряємо: чи ділиться на 3 і чи більше за поточний best
      if (candidate % 3 === 0 && candidate > best) {
        best = candidate; // оновлюємо найкращий результат
      }
    }
  }

  return best; // повертаємо найбільший знайдений варіант
}

