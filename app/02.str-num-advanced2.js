// Solution:
/* Для вирішення потрібно прочитати число зі стандартного вводу, перебрати усі можливі
  заміни однієї цифри, перевіряємо ділення на 3 і вибираємо найбільший кандидат. Отже,
  алгоритм рішення буде:
  1. Перетворюємо число у масив цифр.
  2. Для кожної позиції пробуємо замінити її на іншу цифру (0–9).
    - Пропускаємо випадок, коли цифра лишається тією ж самою.
    - Формуємо нове число.
    - Перевіряємо, чи воно ділиться на 3.
    - Якщо так — зберігаємо як кандидата.
  3. Вибираємо найбільший кандидат.
  4. Виводимо його.
*/

/* Зчитуємо дані з вводу, прибираємо пробіли та переводимо у числа 
  const input = fs.readFileSync(0, "utf8").trim().split("\n"); або задаєм вручну*/
