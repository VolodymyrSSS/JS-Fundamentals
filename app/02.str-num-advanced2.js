/*
  Створіть функцію з назвою ad_bubblesort, яка отримує масив та його розмір. Виконайте
  адаптивний алгоритм сортування бульбашками. Не забудьте використовувати змінну з назвою
  flag для перевірки наявності перекидань.
*/
// Solution:
/* Складність алгоритму бульбашкового сортування становить O(n²). Також, адаптивний
  алгоритм — це алгоритм, який змінює свою поведінку на заданій вхідній послідовності.
  Ми можемо зробити наш алгоритм бульбашкового сортування адаптивним. Нам потрібно 
  написати алгоритм бульбашкового сортування з часом виконання O(n²) у найгіршому випадку
  та O(n) у найкращому випадку, щоб він був адаптивним. Тут найкращий випадок стосується
  випадку, коли масив вже відсортований. Ми будемо використовувати булеву змінну-прапорець
  для керування циклом while, щоб алгоритм зупинився раніше, якщо він був відсортований
  раніше. Отже, ідея адаптивності для Bubble Sort:
   1. Ми додаємо булеву змінну flag, яка показує, чи були перекидання на поточному проході.
   2. Якщо жодного перекидання не відбулося → масив уже відсортований → можна зупинити цикл.
  Таким чином, алгоритм не робить зайвих проходів.
*/
function ad_bubblesort(arr, n) {
  let flag = true; // прапорець для перевірки, чи були перекидання на поточному проході

  // Повторюємо проходи, поки flag істинний
  while (flag) {
    flag = false; // спочатку вважаємо, що масив відсортований
    // Зовнішній цикл — кількість проходів
    for (let i = 0; i < n - 1; i++) {
      // Внутрішній цикл — порівняння сусідніх елементів
      if (arr[i] > arr[i + 1]) {
        // Міняємо місцями сусідні елементи
        let temp = arr[i];
        arr[i] = arr[i + 1];
        arr[i + 1] = temp;

        flag = true; // було перекидання → масив ще не відсортований
      }
    }
  }
  return arr; // Повертаємо відсортований масив
}
