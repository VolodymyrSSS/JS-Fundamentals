/*
  Напишіть функцію firstRepeated, яка отримує цілочисельний масив arr та повертає
  перший елемент, який з'являється більше одного разу під час сканування зліва
  направо. Якщо жоден елемент не повторюється, поверніть -1.
  Додаткова умова: для рішення використайте клас HashMap. Також, не використовуйте
  вбудовані функції JS такі як sets, maps або інші.
*/
// Solution:
function firstRepeated(arr) {
  const map = new HashMap(); // cтворюємо новий об’єкт HashMap
  // проходимось по елементам масиву
  for (const num of arr) {
    /* Якщо елемент вже є у таблиці (containsKey) → повертаємо його як перший повтор.
    Або так: для кожного числа: якщо воно вже є у HashMap → це означає, що ми його
    бачили раніше, отже зараз воно повторюється.
    */
    if (map.containsKey(num)) {
      return num; // перший повторений елемент
    }
    map.put(num, 1); // значення неважливе, просто позначаємо наявність
  }

  return -1; // якщо повторів немає
}
// Tests:
