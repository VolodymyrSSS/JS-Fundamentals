/*
  Hash Table - це структура даних, яка зберігає пари ключ → значення. Ключ
  перетворюється на індекс за допомогою hash‑функції. Основна ідея: доступ
  до елемента відбувається дуже швидко (O(1) у середньому випадку).
  У JavaScript вже є готові інструменти:
  1. Object — проста хеш‑таблиця, де ключі — рядки або символи.
  2. Map — сучасніший варіант, де ключ може бути будь‑яким типом (навіть 
  об’єктом).
  П’ять основних операцій хеш‑таблиці:
  1. Put → у JS це map.set(key, value) = Додає пару ключ‑значення або оновлює
    значення, якщо ключ уже існує.
  2. Get → у JS це map.get(key) = Повертає значення за ключем.
  3. ContainsKey → у JS це map.has(key) = Перевіряє, чи існує ключ у таблиці.
  4. Remove → у JS це map.delete(key) = Видаляє пару ключ‑значення.
  5. Size → у JS це map.size = Повертає кількість пар у таблиці.

  Напишіть клас HashMap з конструктором, який не приймає вхідних даних. 
  1. У конструкторі ініціалізуйте три поля:
  - capacity встановіть на 10;
  - buckets встановіть на масив з 10 порожніх списків (по одному на кожне відро
    для ланцюжка);
  - count встановіть на 0.
  2. Додайте hash метод до класу HashMap. Метод отримує цілочисельний ключ і
    повертає індекс корзини для цього ключа, який обчислюється як key % capacity.
  3. Додайте метод get до класу HashMap. Він отримує цілочисельний ключ і 
    повертає: збережене значення, якщо ключ є в таблиці, або -1, якщо ключ
    відсутній.
  4. Додайте метод containsKey до класу HashMap. Він отримує цілочисельний ключ
  і повертає: 
  - true, якщо ключ зберігається в таблиці;
  - false в іншому випадку.
  5. Додайте метод remove до класу HashMap. Він отримує цілочисельний ключ:
    - якщо ключ є в таблиці, видаліть його пару з корзини та зменште лічильник;
    - якщо ключа там немає, нічого не робіть.
  6. Додайте метод size до класу HashMap. Він не приймає вхідних даних і повертає 
    поточну кількість пар, що зберігаються в таблиці (значення count).
*/
// Solution:
class HashMap {
  constructor() {
    // максимальна кількість "корзин" (buckets)
    this.capacity = 10;

    // створюємо масив із 10 порожніх списків
    this.buckets = [];
    for (let i = 0; i < this.capacity; i++) {
      this.buckets.push([]);
    }
    // можна і так: this.buckets = Array.from({ length: this.capacity }, () => []);

    // кількість пар ключ-значення (спочатку 0)
    this.count = 0;
  }

  // визначення індексу корзини для заданого ключа
  hash(key) {
    /* Рішенням може бути:

    return key % this.capacity;

    Це гарантує - індекс завжди буде від 0 до capacity-1. 
    Але якщо key — від’ємне число або не ціле число, результат може бути від’ємним
    або нецілим, і тоді this.buckets[idx] стає undefined. А undefined не можна 
    ітерувати. Це гарантує, що навіть якщо key від’ємний, індекс буде позитивним.
    Також, якщо випадково передамо у containsKey не число, а undefined або NaN, то 
    hash(key) теж поверне некоректне значення. Тому можна додати перевірку з if:
    
    if (typeof key !== "number" || isNaN(key)) {
      throw new Error("Key must be a valid number");
    }
    return Math.abs(key) % this.capacity;

    Але це ще не все. Крім чисел треба працювати і з рядками і з числами. Тому нам
    потрібно дозволити хешування рядків. Найпростіше — розширити метод hash,
    щоб він міг працювати і з числами, і з рядками:
  */
    if (typeof key === "number" && !isNaN(key)) {
      return Math.abs(key) % this.capacity;
    }

    if (typeof key === "string") {
      let sum = 0;
      for (const ch of key) {
        sum += ch.charCodeAt(0);
      }
      return sum % this.capacity;
    }

    throw new Error("Key must be a number or string");
  }

  //  у методі put ми завжди оновлюємо значення (pair[1]), а ключ (pair[0]) лишається незмінним
  put(key, value) {
    const index = this.hash(key); // визначаємо індекс корзини
    const bucket = this.buckets[index]; // визначаємо яка корзина

    // перевіряємо, чи ключ уже існує
    for (let pair of bucket) {
      if (pair[0] === key) {
        pair[1] = value; // оновлюємо значення бо pair[0] — це ключ а pair[1] — це значення
        return;
      }
    }

    // якщо ключа немає → додаємо нову пару
    bucket.push([key, value]);
    this.count++; // обновляємо рахунок
  }

  get(key) {
    const idx = this.hash(key); // визначаємо індекс корзини
    const bucket = this.buckets[idx]; // взначаємо яка корзина

    for (const pair of bucket) {
      // якщо ключ існує
      if (pair[0] === key) {
        return pair[1]; // повертаємо значення ключа
      }
    }
    return -1; // якщо ключа немає
  }

  containsKey(key) {
    const idx = this.hash(key); // визначаємо індекс для корзини
    // перевіримо всі пари [key, value] у цій корзині
    for (const pair of this.buckets[idx]) {
      // якщо є така пара в корзині
      if (pair[0] === key) {
        return true; // повертаємо true
      }
    }
    return false; // повертаємо якщо нема такої пари в цій корзині
  }

  remove(key) {
    const idx = this.hash(key);
    const bucket = this.buckets[idx];
    // проходимось по усім парам в корзині
    for (let i = 0; i < bucket.length; i++) {
      if (bucket[i][0] === key) {
        bucket.splice(i, 1); // видаляємо пару
        this.count--; // зменшуємо кількість
        return;
      }
    }
  }

  size() {
    return this.count; // просто повертає кількість пар у корзині
  }
}
