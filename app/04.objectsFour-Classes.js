/*
  Зв'язаний список — це послідовність значень, де кожне значення знаходиться 
  у власному вузлі, і кожен вузол містить вказівник на наступний вузол. Список
  знає про свій перший вузол (голову); звідти можна отримати доступ до кожного
  іншого вузла, слідуючи по ланцюжку наступних вказівників.
  На відміну від масиву, зв'язаний список не потребує єдиного суцільного блоку
  пам'яті. Додавання елемента на початок списку займає O(1): просто створіть
  новий вузол і вкажіть його на поточний початок. Компроміс полягає в тому, що
  досягнення n-го елемента займає O(n), оскільки нам доводиться проходити
  ланцюжок по одному вузлу за раз.
  П'ять основних операцій у зв'язаному списку:
  - AddFirst: Додати значення на початок списку.
  - AddLast: Додати значення в кінець списку.
  - Get: Повернути значення за заданим індексом.
  - Remove: Видалити значення за заданим індексом.
  - Size: Повернути кількість значень, що зберігаються на даний момент.

  1. Створіть клас Node з конструктором, який отримує ціле значення. Збережіть його
    як поле класу та ініціалізуйте вказівник next як null. Створіть метод getValue,
    який не отримує вхідних даних та повертає збережене значення;
  2. Створіть клас LinkedList з конструктором, який не отримує вхідних даних. В цьому
    класі ініціалізуйте два поля:
    head встановити на null (список починається з порожнього).
    count встановити на 0.
  3. Додайте метод addFirst до класу LinkedList. Він отримує ціле значення та вставляє
    новий вузол з цим значенням на початок списку. Метод збільшує лічильник.
  4. Додайте метод addLast до класу LinkedList. Він отримує ціле значення та вставляє
    новий вузол з цим значенням у кінець списку. Також лічильник збільшується.
  5. Додайте метод get до класу LinkedList. Він отримує цілочисельний індекс (від 0) та
    повертає: Значення в цій позиції, якщо індекс знаходиться в списку; або -1, якщо
    індекс виходить за межі (від'ємний або занадто велике).
  6. Додайте метод remove до класу LinkedList. Він отримує цілочисельний індекс (від 0):
    a) якщо індекс вказує на існуючий вузол, видаліть цей вузол зі списку та зменште 
    кількість; б) якщо індекс виходить за межі діапазону, нічого не робіть.
  7. Додайте метод size до класу LinkedList. Він не приймає вхідних даних і повертає
    поточну кількість вузлів у списку (значення count).
*/
// Solution:
class Node {
  constructor(value) {
    this.value = value; // зберігаємо передане значення
    this.next = null; // за замовчуванням наступний вузол відсутній
  }

  getValue() {
    return this.value; // повертаємо значення вузла
  }
}

class LinkedList {
  constructor() {
    this.head = null; // список починається порожнім
    this.count = 0; // кількість елементів = 0
  }

  /* Метод приймає значення. Створюємо новий вузол (Node) із цим значенням.
     Робимо так, щоб newNode.next вказував на поточний head. Оновлюємо head
     на новий вузол. Збільшуємо count. */
  addFirst(value) {
    const newNode = new Node(value);
    newNode.next = this.head; // новий вузол вказує на старий head
    this.head = newNode; // тепер head стає новим вузлом
    this.count++; // збільшуємо кількість елементів
  }

  /* Метод приймає значення. Створюємо новий вузол із переданим значенням.
     Якщо список порожній (head === null) → новий вузол стає головою. Інакше
     проходимо список до останнього вузла (current.next === null) і додаємо
     новий вузол у кінець. Збільшуємо count. */
  addLast(value) {
    const newNode = new Node(value);
    // якщо список порожній
    if (!this.head) {
      this.head = newNode; // новий вузол стає головою
    } else {
      // інакше треба знайти останній вузол
      let current = this.head; // починаємо з голови
      // рухаємося по ланцюгу, поки існує наступний вузол
      while (current.next) {
        current = current.next; // рухаємося вперед по ланцюгу
      }
      // коли current.next == null, ми на останньому вузлі
      current.next = newNode; // додаємо новий вузол у кінець
    }
    this.count++; // збільшуємо лічильник елементів
  }

  /* Якщо індекс менший за 0 або більший/рівний count → повертаємо -1.
    Починаємо з head. Проходимо список крок за кроком, рухаючись через 
    next, поки не дійдемо до потрібного індексу. Повертаємо значення 
    вузла (current.getValue()). */
  get(index) {
    // перевірка на вихід за межі
    if (index < 0 || index >= this.count) {
      return -1;
    }

    // починаємо з голови
    let cur = this.head;
    let i = 0;

    // рухаємося вперед, поки не дійдемо до потрібного індексу
    while (i < index) {
      cur = cur.next;
      i++;
    }

    // повертаємо значення вузла
    return cur.getValue();
  }

  /* Якщо індекс менший за 0 або більший/рівний count → нічого не робимо.
     Якщо індекс дорівнює 0 → просто зміщуємо head на наступний вузол 
     (this.head = this.head.next). Інакше проходимо список до вузла перед
     тим, який треба видалити. Змінюємо його next, щоб пропустити вузол,
     який видаляємо. Зменшуємо count. */
  remove(index) {
    // якщо індекс поза межами — нічого не робимо
    if (index < 0 || index >= this.count) {
      return;
    }

    // якщо видаляємо перший елемент
    if (index === 0) {
      this.head = this.head.next;
    } else {
      // знаходимо вузол перед тим, який треба видалити
      let cur = this.head;
      let i = 0;
      while (i < index - 1) {
        cur = cur.next;
        i++;
      }

      // пропускаємо вузол, який видаляємо
      cur.next = cur.next ? cur.next.next : null;
    }

    // зменшуємо кількість елементів
    this.count--;
  }

  size() {
    return this.count;
  }
}

