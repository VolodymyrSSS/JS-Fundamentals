/*
  Напишіть функцію isAnagram, яка отримує два рядки s1 та s2 і повертає, чи є
  вони анаграмами: однаковий мультинабір символів у будь-якому порядку.
  Порівняння чутливе до регістру. Рядки різної довжини ніколи не є анаграмами.
  Додаткова умова: для рішення використайте клас HashMap з попереднього завдання.
  Також, не використовуйте вбудовані функції JS такі як sets, maps або інші.
*/
// Solution:
/* Алгоритм рішення буде таким:
  !. Якщо довжини рядків різні → одразу повертаємо false.
  2. Створюємо новий HashMap.
  3. Для кожного символу в s1:
    - Якщо символ уже є у таблиці → збільшуємо його лічильник.
    - Інакше додаємо символ зі значенням 1.
  4. Для кожного символу в s2:
    - Якщо символ немає у таблиці → повертаємо false.
    - Інакше зменшуємо його лічильник.
    - Якщо після зменшення значення стає 0 → видаляємо символ (remove).
  5. Якщо після проходження всіх символів таблиця порожня → рядки є анаграмами.
*/
function isAnagram(s1, s2) {
  if (s1.length !== s2.length) {
    return false;
  }

  const map = new HashMap();

  // рахуємо символи у s1
  for (const ch of s1) {
    if (map.containsKey(ch)) {
      const count = map.get(ch);
      map.put(ch, count + 1);
    } else {
      map.put(ch, 1);
    }
  }

  // віднімаємо символи у s2
  for (const ch of s2) {
    if (!map.containsKey(ch)) {
      return false;
    }
    const count = map.get(ch);
    if (count === 1) {
      map.remove(ch);
    } else {
      map.put(ch, count - 1);
    }
  }

  // якщо всі символи збалансовані → анаграма
  return map.size() === 0;
}
// Tests:
console.log(isAnagram("listen", "silent")); // true
console.log(isAnagram("hello", "world")); // false
console.log(isAnagram("a", "a")); // true
console.log(isAnagram("abc", "abcd")); // false

