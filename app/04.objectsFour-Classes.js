/*
  Напишіть функцію firstNonRepeating, яка отримує цілочисельний масив arr та
  повертає перший елемент, який з'являється рівно один раз (у порядку сканування).
  Якщо кожен елемент повторюється, повертає -1.
  Додаткова умова: для рішення використайте клас HashMap з попереднього завдання.
  Також, не використовуйте вбудовані функції JS такі як sets, maps або інші.
*/
// Solution:
/*
  1. Створюємо новий HashMap.
  2. Проходимо масив і рахуємо кількість появ кожного числа.
    - Якщо ключ уже є → збільшуємо лічильник.
    - Інакше додаємо зі значенням 1.
  3. Другим проходом по масиву (щоб зберегти порядок) перевіряємо:
    - Якщо для елемента лічильник дорівнює 1 → повертаємо його як перший неповторний.
    - Якщо жодного такого немає → повертаємо -1.
*/
function firstNonRepeating(arr) {
  const map = new HashMap();

  // перший прохід: рахуємо кількість
  for (const num of arr) {
    if (map.containsKey(num)) {
      const count = map.get(num);
      map.put(num, count + 1);
    } else {
      map.put(num, 1);
    }
  }

  // другий прохід: шукаємо перший з count == 1
  for (const num of arr) {
    if (map.get(num) === 1) {
      return num;
    }
  }

  return -1;
}
// Tests:
console.log(firstNonRepeating([1, 2, 2, 3, 1])); // 3
console.log(firstNonRepeating([1, 1, 2, 2])); // -1
console.log(firstNonRepeating([5])); // 5
console.log(firstNonRepeating([4, 4, 5, 6, 5])); // 6

