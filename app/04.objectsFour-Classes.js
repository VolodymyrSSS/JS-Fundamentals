/*
  Напишіть функцію mostFrequent, яка отримує непорожній цілочисельний масив
  arr та повертає елемент, що зустрічається найчастіше. Якщо два елементи 
  мають однакову кількість, повертається той, який досяг цієї кількості першим
  (найраніше в порядку сканування).
  Додаткова умова: для рішення використайте клас HashMap з попереднього завдання.
  Також, не використовуйте вбудовані функції JS такі як sets, maps або інші.
*/
// Solution:
/*
  1.Створюємо новий HashMap.
  2.Ітеруємо масив зліва направо.
    - Якщо елемент уже є у таблиці → збільшуємо його лічильник.
    - Інакше додаємо його зі значенням 1.
  3.Паралельно відстежуємо:
    - maxCount — найбільшу кількість повторів.
    - result — елемент, який першим досяг цього максимуму.
  4.Якщо новий елемент досягає більшого count → оновлюємо result.
  5.Якщо він лише зрівнявся з maxCount, залишаємо попередній (бо він був раніше).
*/
function mostFrequent(arr) {
  const map = new HashMap();
  let maxCount = 0;
  let result = arr[0]; // масив непорожній, тому можна взяти перший елемент

  for (const num of arr) {
    let count;
    if (map.containsKey(num)) {
      count = map.get(num) + 1;
      map.put(num, count);
    } else {
      count = 1;
      map.put(num, count);
    }

    // якщо count > maxCount → оновлюємо результат
    if (count > maxCount) {
      maxCount = count;
      result = num;
    }
    // якщо count == maxCount → залишаємо попередній result
  }

  return result;
}
// Tests:
console.log(mostFrequent([1, 2, 2, 3, 3, 3])); // 3
console.log(mostFrequent([4, 4, 5, 5])); // 4 (бо 4 перший досяг count=2)
console.log(mostFrequent([7])); // 7

