/*
  Напишіть функцію twoSum, яка отримує цілочисельний масив arr та ціле число
  target, і повертає індекси двох елементів, значення яких у сумі дорівнюють
  target. Функція повинна повертати індекси у порядку зростання: [smaller_index,
  larger_index]. Кожен вхідний рядок має рівно одну дійсну пару.
  Додаткова умова: для рішення використайте клас HashMap з попереднього завдання.
  Також, не використовуйте вбудовані функції JS такі як sets, maps або інші.
*/
// Solution:
function twoSum(arr, target) {
  const map = new HashMap(); // cтворюємо новий HashMap.
  // iтеруємо масив зліва направо
  for (let i = 0; i < arr.length; i++) {
    const num = arr[i]; // для кожного елемента num обчислюємо:
    const complement = target - num; // знайдений елемент масиву, який в сумі з і дає target
    // Якщо complement вже є у таблиці → повертаємо індекси [map.get(complement), i]
    if (map.containsKey(complement)) {
      const j = map.get(complement); // індекс знайденого елемента що в сумі з і дає target
      return [j, i]; // повертаємо індекси у порядку [менший, більший]
    }
    // Інакше додаємо num у таблицю зі значенням = його індекс.
    // тобто зберігаємо число як ключ, індекс як значення
    map.put(num, i);
  }
  // оскільки задача гарантує одну правильну пару, ми завжди знайдемо її
  return [];
}
// Tests:
console.log(twoSum([2, 7, 11, 15], 9)); // [0, 1]
console.log(twoSum([3, 3], 6)); // [0, 1]
console.log(twoSum([1, 2, 3, 4], 7)); // [2, 3]
console.log(twoSum([0, 4, 3, 0], 0)); // [0, 3]

