class BinaryTree {
  constructor() {
    // Ініціалізуємо корінь дерева як null (спочатку дерево порожнє)
    this.root = null;
  }

  getRoot() {
    // Повертає корінь дерева (або null, якщо його ще немає)
    return this.root;
  }

  setRoot(newRoot) {
    // Встановлює новий корінь дерева
    this.root = newRoot;
  }

  buildTree(treeString) {
    // Парсимо рядок у JavaScript-структуру (масиви/об'єкти)
    const treeArray = JSON.parse(treeString);

    // Рекурсивна функція для побудови вузлів
    function buildNode(arr) {
      if (arr === null) return null; // якщо null → немає вузла

      const node2 = new Node2(); // створюємо вузол
      node2.setValue(arr[0]); // перший елемент — значення

      node2.setLeft(buildNode(arr[1])); // другий елемент — ліва підструктура
      node2.setRight(buildNode(arr[2])); // третій елемент — права підструктура

      return node2;
    }

    // Будуємо дерево й встановлюємо корінь
    this.root = buildNode(treeArray);
  }
}

