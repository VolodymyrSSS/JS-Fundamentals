// Solution via dynamic programming:
/*
  dp — це скорочення від dynamic programming (динамічне програмування). Ідея
  проста: ми зберігаємо вже обчислені результати для менших підзадач, щоб не 
  рахувати їх знову. У цій задачі:
    Ми будуємо масив поступово:
    dp[1] = 1
    dp[2] = 2
    dp[i] = dp[i-1] + dp[i-2] де dp[i] буде означає кількість способів дістатися
                              до сходинки i.
*/
function climb_stairs3(n) {
  if (n <= 2) return n; // базові випадки

  // dp[i] буде зберігати кількість способів дістатися до сходинки i
  const dp = new Array(n + 1); // створюємо масив довжиною n + 1, щоб індекси йшли від 0 до n.
  dp[1] = 1;
  dp[2] = 2;

  for (let i = 3; i <= n; i++) {
    dp[i] = dp[i - 1] + dp[i - 2]; // формула DP - динамічного програмування
  }

  return dp[n];
}
