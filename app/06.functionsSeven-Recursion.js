// Solution via Recursion:
/* Ідея рекурсивного рішення:
    1. Базовий випадок: якщо рядок порожній або має довжину 1
      тоді повертаємо цей рядок як є.
    2. Рекурсивний випадок: беремо останній символ і додаємо
      результат реверсу решти рядка.
*/
function reverseStringRecursive(str) {
  // Базовий випадок
  if (str.length <= 1) {
    return str;
  }

  // Рекурсивний випадок
  return str[str.length - 1] + reverseStringRecursive(str.slice(0, -1));
  // тут str.slice(0, -1) повертає рядок без останнього символу.
  // а тут рішення таке: беремо перший символ і переносимо його в кінець,
  // а решту рядка реверсуємо рекурсивно:
  // return reverseString(str.slice(1)) + str[0];
}
