/*
  Щотижня в Coddy більше користувачів, ніж попереднього тижня. Функція рекурсії,
  яка представляє кількість користувачів Coddy за тиждень, виглядає так:
  Якщо попереднього тижня було x користувачів, а цього тижня – y користувачів,
  то наступного тижня Coddy матиме x + 3y користувачів. Отже, першого тижня
  Coddy мав 0 користувачів, а другого – 1 користувача.
  Напишіть функцію getUsers, яка отримує ціле число n та повертає кількість
  користувачів Coddy за n-й тиждень.

  Приклад 1:
  Вхідні дані: 3
  Очікуваний вихід: 3 бо на третьому тижні Coddy матиме кількість користувачів,
  яку він мав на першому тижні, плюс подвоєну кількість користувачів, яку він мав
  на другому тижні, що дасть 1*0+3*1=3.

  Приклад 2:
  Вхідні дані: 4
  Очікуваний вихідний результат: 10

  Приклад 3:
  Вхідні дані: 5
  Очікуваний вихідний результат: 33
  
  Обмеження: 1 < n < 20
*/
// Solution:
/*
  Ми маємо рекурентне співвідношення для щотижневих користувачів Кодді:
    𝑈𝑛 = 𝑈𝑛−2 + 3⋅𝑈𝑛−1
  з базовими випадками:
    Тиждень 1: 𝑈1 = 0
    Тиждень 2: 𝑈2 = 1
  Нам потрібно обчислити 𝑈𝑛 для 1 < 𝑛 <20.

  Алгоритм рішення:
  1. Базові випадки
    - Якщо 𝑛 = 1, повернути 0.
    - Якщо 𝑛 = 2, повернути 1.
  2. Повторюваність для 𝑛 ≥ 3, обчислити рекурсивно:
    𝑈𝑛 = 𝑈𝑛−2 + 3⋅𝑈𝑛−1
  3. Вибір реалізації рішення через :
    a) Ітераційний DP (цикл від 3 до n та збереження результатів у масиві) бо 
       ітерація безпечніша для обмежень (без переповнення стеку, швидко);
    b) Рекурсивна функція (прямий переклад формули).
*/
function getUsers1(n) {
  // базовий випадок
  if (n === 1) return 0;
  if (n === 2) return 1;

  // ініціалізація перших двох тижнів
  let u1 = 0; // week 1
  let u2 = 1; // week 2
  let uN = 0;

  // підрахунок користувачів для 3..n використовуючи закономірність збільшення
  for (let i = 3; i <= n; i++) {
    uN = u1 + 3 * u2; // закономірність
    u1 = u2; // використання закономірності для подальших тижнів
    u2 = uN;
  }

  return uN;
}
