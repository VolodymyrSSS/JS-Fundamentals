// Solution via recursion (simple version):
/* Ідея:
  - Базовий випадок: якщо рядок порожній або має довжину 1 → це паліндром.
  - Рекурсивний випадок: порівнюємо перший і останній символи. Якщо вони
    однакові → рекурсивно перевіряємо середину рядка. Якщо різні → повертаємо false.
*/

function isPalindromeRecursiveSimple(s) {
  // базовий випадок
  if (s.length <= 1) {
    return true;
  }

  // порівнюємо перший і останній символи
  if (s[0] !== s[s.length - 1]) {
    // якщо перший і останній символи різні → не паліндром
    return false;
  }

  // рекурсивний виклик для середини рядка
  return isPalindromeRecursiveSimple(s.slice(1, s.length - 1));
}
