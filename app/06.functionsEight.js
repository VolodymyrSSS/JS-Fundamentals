/*
  Вам надано масив, що містить n різних чисел, взятих із 0, 1, 2, ..., n, за
  винятком одного числа, якого не вистачає. Напишіть функцію findMissingNumber,
  яка знаходить та повертає відсутнє число.
*/
// Solution via sort (O(n log n)):
/* Алгоритм рішення
  1. Відсортувати масив.
  2. Перевірити кожну позицію: якщо індекс ≠ значення → це пропущене число.
  3. Якщо всі збігаються → пропущене число = n.
*/
function findMissingNumberSort(nums) {
  nums.sort((a, b) => a - b); // сортуємо масив

  // ітеруємо по всім елементам масиву
  for (let i = 0; i < nums.length; i++) {
    if (nums[i] !== i) return i; // якщо індекс недорівнює значенню - це пропущене
  }

  return nums.length;
}
// Tests:
