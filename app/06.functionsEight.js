/*
  Напишіть функцію з назвою isPalindrome, яка визначає, чи є рядок паліндромом.
  Паліндром – це слово або фраза, яка читається однаково як у зворотному, так і
  в прямому порядку. Функція повинна приймати рядок на вхід і повертати true,
  якщо це паліндром, і false в іншому випадку.
*/
// Solution:
/*
  Алгоритм рішення:
  1. Взяти рядок s.
  2. Перевірити символи з обох кінців: перший з останнім, другий з передостаннім
    і так далі.
  3. Якщо всі пари збігаються — це паліндром.
  4. Якщо хоч одна пара не збігається — повернути false.
*/
function isPalindrome1(s) {
  // перетворюємо рядок у масив символів для зручності
  const chars = s.split("");

  // два індекси: зліва і справа
  let left = 0;
  let right = chars.length - 1;

  // перевіряємо поки індекси не перетнуться
  while (left < right) {
    if (chars[left] !== chars[right]) {
      return false; // якщо символи не збігаються — не паліндром
    }
    left++; // рухаємося вправо
    right--; // рухаємося вліво
  }

  return true; // якщо всі символи збіглися
}
