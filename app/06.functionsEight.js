// Solution via Set:
function findMissingNumberSet(nums) {
  const n = nums.length; // визначаємо довжину масиву

  const set = new Set(nums); // визначаємо множину унікальних значень

  // ітеруємо по всіх елементах масиву та порівнюємо їх із множиною усіх значень
  for (let i = 0; i <= n; i++) {
    // якщо множина унікальних значень не має значення в порядку ітерації - це пропущене
    if (!set.has(i)) return i;
  }
}
console.log(findMissingNumberSet([9, 6, 4, 2, 3, 5, 7, 0, 1])); // 8

// Solution via sum formula:
/*
  Формула суми
  Сума чисел від 0 до n дорівнює (𝑛⋅(𝑛+1))/2
  Відняти суму елементів масиву → отримаємо пропущене число.
  Це працює за O(n) часу та O(1) пам’яті.
*/
function findMissingNumberSum(nums) {
  const n = nums.length; // довжина масиву = кількість чисел, але пропущене одне

  // обчислюємо очікувану суму від 0 до n
  const expectedSum = (n * (n + 1)) / 2;

  // обчислюємо фактичну суму елементів масиву
  let actualSum = 0;
  for (let i = 0; i < n; i++) {
    actualSum += nums[i];
  }

  // різниця = пропущене число
  return expectedSum - actualSum;
}
console.log(findMissingNumberSum([0, 1])); // 2

// Solution via method XOR (O(n)):
/*
  Ідея:
  XOR усіх чисел від 0 до n.
  XOR усіх чисел у масиві.
  Результат = пропущене число (бо всі інші взаємно «обнуляться»).
*/
function findMissingNumberXOR(nums) {
  const n = nums.length;
  let xorAll = 0;
  let xorNums = 0;

  // XOR від 0 до n
  for (let i = 0; i <= n; i++) xorAll ^= i;

  // XOR усіх елементів масиву
  for (let i = 0; i < n; i++) xorNums ^= nums[i];

  return xorAll ^ xorNums;
}
console.log(findMissingNumberXOR([1])); // 0
console.log(findMissingNumberXOR([1, 4, 3, 5, 6, 8, 7, 0])); // 2

