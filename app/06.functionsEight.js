/*
  Напишіть функцію з rotateArray, яка за заданим цілочисельним масивом та 
  числом k повертає масив праворуч на k кроків, де k невід'ємне, та повертає
  повернутий масив. Приклад:
    Вхід: nums = [1,2,3,4,5,6,7], k = 3
    Вихід: [5,6,7,1,2,3,4]
  Пояснення:
    Поворот на 1 крок праворуч: [7,1,2,3,4,5,6]
    Поворот на 2 кроки праворуч: [6,7,1,2,3,4,5]
    Поворот на 3 кроки праворуч: [5,6,7,1,2,3,4]
*/
// Solution:
/* Алгоритм рішення
  1. Визначаєм довжину масиву = n.
  2. Якщо k > n, то достатньо взяти k % n (бо ротація на n кроків
     повертає масив у початковий стан).
  3. Розділити масив на дві частини:
     - останні k елементів,
     - решта елементів.
  4. Об’єднати їх у новому порядку.
*/
function rotateArray1(nums, k) {
  const n = nums.length;
  if (n === 0) return [];

  // нормалізуємо k
  k = k % n;

  // беремо останні k елементів + решту
  const rotated = nums.slice(n - k).concat(nums.slice(0, n - k));

  return rotated;
}
