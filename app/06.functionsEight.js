/*
 Напишіть функцію singleChar, яка отримує рядок s, кожен символ у s 
 зустрічається двічі, окрім одного, повертає з функції символ, який зустрічається
 лише один раз!
  Приклад:
    Вхідні дані - "aabdb"
    Очікуваний вихідний дані - "d", бо  "a" та "b" зустрічаються двічі, а "d" 
    зустрічається лише один раз.
*/
// Solution:
/*
  1. Створюємо об’єкт‑лічильник для підрахунку кількості входжень кожного символу.
  2. Проходимо по рядку й збільшуємо лічильник для кожного символу.
  3. Після цього шукаємо символ, який зустрівся лише один раз.
  4. Повертаємо його як результат.
*/
function singleChar1(s) {
  const count = {}; // створюємо об’єкт для підрахунку кількості входжень символів

  for (let char of s) {
    // проходимо по кожному символу рядка
    count[char] = (count[char] || 0) + 1; // збільшуємо лічильник для символа
  }

  for (let char in count) {
    // перевіряємо всі символи у лічильнику
    if (count[char] === 1) {
      // якщо символ зустрівся лише один раз
      return char; // повертаємо його
    }
  }
}
