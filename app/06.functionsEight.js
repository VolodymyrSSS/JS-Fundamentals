/*
  Якщо у вас є N грошей, і ви хочете купити подарунки для своїх друзів. Магазин
  поруч продає подарунок за ціною A доларів, але магазин далі продає їх за меншу
  ціну - B доларів (A > B). Обчисліть, скільки ще подарунків ви можете купити,
  якщо підете до магазину далі.
  Напишіть функцію canBuyMoreGifts, якій задано три натуральні числа N, A та B
  з вхідних даних. Поверніть, скільки ще подарунків ви можете купити за ціною B
  доларів замість ціни A доларів. Для тестування:
    - Вхідні дані: 22 6 5; Вихідні дані: 1
    - Вхідні дані: 30 7 4; Вихідні дані: 3
*/
// Solution:
/* Алгоритм рішення:
  1. Маємо 𝑁 грошей.
  2. У ближньому магазині ціна подарунка 𝐴.
     Кількість подарунків: near=⌊𝑁/𝐴⌋.
  3. У дальньому магазині ціна подарунка 𝐵.
     Кількість подарунків: far=⌊𝑁/𝐵⌋.
  4. Різниця: extra=far−near
  5. Вивести extra.

  Отже, ми просто ділимо гроші на ціну подарунка й беремо цілу частину. Потім
  різниця показує, скільки більше подарунків можна купити в дешевшому магазині.
*/
function canBuyMoreGifts(N, A, B) {
  const near = Math.floor(N / A);
  const far = Math.floor(N / B);

  return far - near;
}
