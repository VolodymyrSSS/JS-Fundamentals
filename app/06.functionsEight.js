// [3,4,5,1,2]

// Solution via array rotary in place
/*
  Ідея алгоритму (Reverse Method)
  1. Нормалізуємо k = k % n.
  2. Реверсуємо весь масив.
  3. Реверсуємо перші k елементів.
  4. Реверсуємо решту n - k елементів.
  Таким чином елементи стають у правильному порядку.
*/
function rotateArray2(nums, k) {
  const n = nums.length;
  if (n === 0) return [];

  k = k % n;

  // допоміжна функція для реверсу частини масиву
  function reverse(arr, start, end) {
    while (start < end) {
      [arr[start], arr[end]] = [arr[end], arr[start]];
      start++;
      end--;
    }
  }

  // 1. реверс всього масиву
  reverse(nums, 0, n - 1);

  // 2. реверс перших k елементів
  reverse(nums, 0, k - 1);

  // 3. реверс решти
  reverse(nums, k, n - 1);

  return nums;
}
console.log(rotateArray2([1, 2, 3, 4, 5, 6, 7], 3));
// [5,6,7,1,2,3,4]

// Solution via cycle replacement:
/*
  Кожен елемент треба перемістити на позицію (i + k) % n.
  Ми йдемо по масиву циклами: починаємо з індексу 0, переносимо його
  значення на нове місце, беремо те, що там було, і переносимо далі,
  доки не повернемося в початкову точку.
  Потім починаємо новий цикл із наступного ще не переміщеного індексу.
  У результаті всі елементи опиняються на правильних місцях без додаткової пам’яті.
*/
function rotateArray3(nums, k) {
  const n = nums.length;
  if (n === 0) return [];

  k = k % n;
  let count = 0; // скільки елементів вже перемістили

  for (let start = 0; count < n; start++) {
    let current = start;
    let prev = nums[start];

    do {
      const next = (current + k) % n;
      const temp = nums[next];
      nums[next] = prev;
      prev = temp;
      current = next;
      count++;
    } while (start !== current);
  }

  return nums;
}
console.log(rotateArray3([1, 2, 3, 4, 5, 6, 7], 3));
// [5,6,7,1,2,3,4]
