/*
  Ваш учитель записав у вашому зошиті три числа A, B та C. Розставте математичні
  символи так, щоб операція між першими двома числами дорівнювала третьому числу.
  Напишіть функцію equation, яка отримує три натуральні числа A, B та C з вхідних
  даних. Виведіть шукане рівняння на екран. (Використовуйте +, -, *, / та =). У
  разі, якщо не можливо підібрати математичні символи для існуючих чисел. виведіть 
  "Немає коректного рівняння". Для тестування:
  Вхідні дані: 4 2 6; Вихідні дані: 4+2=6
  Вхідні дані: 9 3 27; Вихідні дані: 9*3=27
*/
// Solution:
/* Алгоритм рішення
  1. Прочитати три числа 𝐴,𝐵,𝐶.
  2. Перевірити по черзі всі можливі операції::
    Якщо А + В = С то вивести 𝐴+В=𝐶
    Якщо А - В = С то вивести 𝐴-В=𝐶
    Якщо А * В = С то вивести 𝐴*В=𝐶
    Якщо А / В = С i B ≠ 0 то вивести 𝐴/В=𝐶
  3. Завершити, коли знайдено правильну операцію.
*/
function equation(A, B, C) {
  if (A + B === C) return `${A}+${B}=${C}`;
  if (A - B === C) return `${A}-${B}=${C}`;
  if (A * B === C) return `${A}*${B}=${C}`;
  if (B !== 0 && A / B === C) return `${A}/${B}=${C}`;
  return "No valid equation";
}
// Tests:
console.log(equation(4, 2, 6)); // 4+2=6
console.log(equation(9, 3, 27)); // 9*3=27
console.log(equation(48, 6, 8)); // 48/6=8
console.log(equation(48, 7, 8)); // "No valid equation"

