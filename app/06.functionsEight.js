/*
  Трикутник Паскаля — це трикутний масив чисел, де кожне число є сумою двох
  чисел безпосередньо над ним. Перший рядок містить число 1, а кожен наступний
  рядок починається та закінчується 1. Трикутник Паскаля має багато математичних
  та комбінаторних застосувань, включаючи обчислення біноміальних коефіцієнтів
  та ймовірностей.
  Ось трикутник Паскаля розміром 5:
        1 
       1 1
      1 2 1
     1 3 3 1
    1 4 6 4 1
  Напишіть функцію pascal, яка отримує ціле число n та виводить рядок, що
  представляє двовимірний масив трикутника Паскаля розміром n. Приклади:
  Вхід: 5
  Вихід: [[1],[1,1],[1,2,1],[1,3,3,1],[1,4,6,4,1]]
  Вхід: 3
  Вихід: [[1],[1,1],[1,2,1]]
  Виводьте будь-які пробіли!
*/
// Solution:
/* Алгоритм рішення буде:
  1. Починаємо з порожнього масиву triangle.
  2. Для кожного row від 0 до n-1:
    а. Створюємо масив current довжиною row+1.
    б. Записуємо current[0] = 1 і current[row] = 1.
    в. Для внутрішніх позицій col від 1 до row-1:
      current[col] = triangle[row-1][col-1] + triangle[row-1][col];
    г. Додаємо current у triangle.
  3. Повертаємо triangle як рядок (JSON.stringify(triangle)).
*/
function pascal(n) {
  const triangle = []; // головний масив для всіх рядків
  // Проходимось по кожному ряду row
  for (let row = 0; row < n; row++) {
    /* У трикутнику Паскаля рядок номер row має рівно row + 1 елементів.
     Наприклад:
     Рядок 0 → [1] → 1 елемент
     Рядок 1 → [1,1] → 2 елементи
     Рядок 2 → [1,2,1] → 3 елементи
     Рядок 3 → [1,3,3,1] → 4 елементи
     Тому ми створюємо масив довжиною row + 1, щоб у ньому вистачило місця
     для всіх чисел цього рядка. */
    const current = new Array(row + 1);

    current[0] = 1; // перший елемент завжди 1
    current[row] = 1; // останній елемент теж 1

    // заповнюємо внутрішні елементи (якщо вони є)
    for (let col = 1; col < row; col++) {
      // внутрішні елементи = сума двох чисел над ним або кожен елемент = сума двох елементів з попереднього рядка
      current[col] = triangle[row - 1][col - 1] + triangle[row - 1][col];
    }

    triangle.push(current); // додаємо рядок у трикутник
  }

  return JSON.stringify(triangle); // повертаємо як рядок
}
