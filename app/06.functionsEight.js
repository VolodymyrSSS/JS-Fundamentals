console.log(findPair1([3, 3, 3, 1], 3)); // false
console.log(findPair1([5, 7, 1, 2], 9)); // true (7 + 2)

// Solution via doubled loops:
/*
  Версія з подвійним циклом перевіряє усі можливі пари в масиві. Це простіше
  для розуміння, але працює повільніше (O(n²)).
*/
function findPair2(arr, k) {
  // проходимо по кожному елементу масиву
  for (let i = 0; i < arr.length; i++) {
    // для кожного елемента перевіряємо всі наступні елементи
    for (let j = i + 1; j < arr.length; j++) {
      // якщо сума двох елементів дорівнює k
      if (arr[i] + arr[j] === k) {
        return true; // знайшли пару
      }
    }
  }
  return false; // якщо жодна пара не підійшла
}
