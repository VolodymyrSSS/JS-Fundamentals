/*
  Майже паліндром. Паліндром – це рядок, який читається однаково як у зворотному,
  так і в прямому порядку читання. Наприклад: "racecar", "mom", "madam" – це все
  паліндроми, а "father" – ні.
  Майже паліндром – це рядок, який або є паліндромом, або може бути перетворений
  на паліндром, змінивши в ньому лише 1 символ. Наприклад: "racecar", "mom",
  "madam" – це майже паліндроми, оскільки вони також є паліндромами. "racebar"
  також є майже паліндромом, оскільки він може перетворитися на паліндром, змінивши
  символ 'b' на символ 'c' (або навпаки, змінивши 'c' на 'b'). "abcdcab" не є майже
  паліндромом, оскільки для того, щоб перетворитися на паліндром, його потрібно
  змінити щонайменше 2 символи.
  Напишіть функцію з назвою isAlmostPalindrome, яка отримує рядок на вхід, повертає
  true, якщо рядок є майже паліндромом, і повертає false в іншому випадку.
*/
// Solution:
/*
  Algorithm:
  1. Встановити два вказівники:
    - left = 0 (початок рядка)
    - right = s.length - 1 (кінець рядка)
  2. Порівняти символи:
    До тих пір доки left < right:
      - Якщо s[left] === s[right], рухатися всередину (left++, right--).
      - Якщо вони відрізняються, збільшувати mismatchCount на значення.
  3. Перевірити кількість невідповідностей:
    - Якщо mismatchCount > 1, повернути false (потрібно більше однієї зміни).
    - Якщо mismatchCount <= 1, повернути true (вже є паліндромом або може бути 
      виправлено однією зміною).
*/
function isAlmostPalindrome(s) {
  // створюємо два вказівники
  let left = 0;
  let right = s.length - 1;

  // підрахунок невідповідностей
  let mismatchCount = 0;

  // ітеруємо до тих пір доки вказівники не зустрінуться в середині
  while (left < right) {
    if (s[left] !== s[right]) {
      // символи відрізняються → збільшити лічильник невідповідностей
      mismatchCount++;
      // якщо більше ніж 1 невідповідність, це не підпадає під визначення "майже паліндром"
      if (mismatchCount > 1) return false;
    }
    // рухаємо вказівники всередину (до центру рядка)
    left++;
    right--;
  }

  // якщо 0 або 1 невідповідність → це підпадає під визначення "майже паліндром"
  return true;
}
