/*
  Вам задано послідовність, яка починається з 1, і після кожного елемента 
  додана послідовність збільшується, але починається кожного разу із самого
  початку, ось як показано тут: 112123123412345123456
  Отже, функція digit отримує аргументом натуральне число N. Поверніть N-ну
  цифру заданої із заданої послідовності. Для тестування:
    - Вхідні дані: 10; вихідні дані: 17, бо 112123123[4]12345123456
    - Вхідні дані: 17; вихідні дані: 2, бо: 1121231234123451[2]34561234567
*/
// Solution:
/* Алгоритм рішення: з двома циклами
  1. Зовнішній цикл: генерує блоки 1, 12, 123, …
  2. Внутрішній цикл: додає цифри всередині кожного блоку.
  3. Ми йдемо по блоках, доки не дійдемо до потрібної позиції n.
  4. Як тільки досягли n‑го символа — повертаємо його.
*/
function digit1(n) {
  let length = 0; // лічильник, який показує, скільки цифр ми вже пройшли в загальній послідовності
  /*
    У задачі ми не знаємо наперед, у якому блоці лежить N‑на цифра.
    Тому ми поступово «рахуємо» всі цифри, поки не дійдемо до позиції n.
       - Спочатку length = 0, бо ми ще не пройшли жодної цифри.
       - Кожного разу, коли внутрішній цикл додає нову цифру, ми робимо length++.
       - Коли length === n, ми знаємо, що поточна цифра — саме та, яку треба повернути.
  */

  /* Зовнішній цикл для блоків - це i, що означає номер блоку (довжина блоку = i)
     Якщо ми пишемо i < n, то ми генеруємо аж до блоку номер n, але n — це позиція
     в загальній послідовності, а не номер блоку, тому ми не пишем і < n. Тому
     ми повинні йти блок за блоком і рахувати загальну кількість цифр, доки не дійдемо до n.*/
  for (let i = 1; ; i++) {
    // внутрішній цикл для цифр у блоці
    for (let j = 1; j <= i; j++) {
      length++; // додаємо ще одну цифру

      // якщо ми дійшли до потрібної позиції
      if (length === n) {
        return String(j); // повертаємо рядок-число j
      }
    }
  }
}
// Tests:
console.log(digit1(10)); // 4
console.log(digit1(17)); // 2

/* Алгоритм рішення:
  Ця задача про «зростаючу послідовність» виглядає так:
    1
    12
    123
    1234
    12345
    ...
  Але вона записується в одну стрічку: 112123123412345123456...
  Тому логіка буде: 
  1. Ми будуємо послідовність блоками:
    1
    12
    123
    1234
    …
  2. Потім з’єднуємо їх у рядок.
  3. Потрібно знайти N‑ну цифру цього рядка.
*/
function digit2(n) {
  let seq = ""; // тут будемо накопичувати послідовність
  let i = 1; // починаємо з числа 1

  // один цикл зовні (while) і один всередині (for)
  // Зовнішній цикл while (seq.length < n) - ми генеруємо блоки доти, доки не досягнемо потрібної довжини.
  while (seq.length < n) {
    // Внутрішній цикл for (let j = 1; j <= i; j++) генерує сам блок: цифри усередині блоку - 123...
    for (let j = 1; j <= i; j++) {
      seq += j; // додаємо блок "123..."
    }
    i++; // переходимо до наступного блоку
  }

  // повертаємо N‑ну цифру (індекси з 0 → тому n-1)
  return seq[n - 1];
}
// Tests:
console.log(digit2(10)); // 4
console.log(digit2(17)); // 2

