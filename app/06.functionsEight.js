/*
 Напишіть функцію findDominoPair, яка отримує масив "dominos" arr та цільові
 числа k та l. Domino — це рядок, що представляє пару з 2 цілих чисел у такому
 форматі: "(3;5)". Функція повинна повертати true, якщо в arr існують два доміно
 "(ai;bi)" та "(aj;bj)", а ai + aj = k та bi + bj = l, інакше повертає false.
  Приклад:
  Вхідні дані - arr = ["(1;3)", "(2;4)", "(3;1)", "(2;2)"], k = 5, l = 3
  Очікуваний вихід - true бо достатньо пари "(3;1)" та "(2;2)", яка існує в arr,
                      3 + 2 = 5 та 1 + 2 = 3.
  Примітка: arr не є відсортованим масивом, і можна припустити, що доміно
  не обертаються.
*/
// Solution:
/*
  1. Розберем кожен рядок доміно на два цілі числа (a, b).
    Приклад: "(3;5)" → a = 3, b = 5.
    Тобто парсимо рядки: кожне доміно типу "(3;5)" перетворюємо на масив [3, 5].
  2. Перевірте всі пари доміно (груба сила тут допустима, оскільки обмеження малі).
    Через подвійний цикл перебирає всі можливі комбінації.
    Для кожної пари (ai, bi) та (aj, bj) перевіряємо, чи ai + aj === k та bi + bj === l.
  3. Якщо така пара існує → поверніть true.
    Інакше → поверніть false.
*/
function findDominoPair(arr, k, l) {
  // перетворюємо кожен доміно-рядок у пару чисел
  const dominos = arr.map((str) => {
    const parts = str.slice(1, -1).split(";"); // видаляємо дужки і розділяємо по ";"
    return [parseInt(parts[0]), parseInt(parts[1])]; // повертаємо пару чисел у масиві
  });

  // перевіряємо всі можливі пари доміно
  for (let i = 0; i < dominos.length; i++) {
    for (let j = i + 1; j < dominos.length; j++) {
      const [ai, bi] = dominos[i]; // перше доміно
      const [aj, bj] = dominos[j]; // друге доміно

      // перевіряємо умову: сума перших чисел = k, сума других чисел = l
      if (ai + aj === k && bi + bj === l) {
        return true; // знайшли пару
      }
    }
  }

  return false; // пари не знайдено
}
