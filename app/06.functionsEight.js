/*
  Вам задано сигнал у вигляді рядка нулів та одиниць. Поверніть довжину 
  найдовшої послідовності одиниць. Приклад:
    Вхідні дані: 0110111001011110000000011
    Очікуваний вихідний результат: 4
*/
// Solution:
/* Алгоритм рішення:
  1. Ініціалізація лічильників
    - maxCount = 0 → зберігає найдовшу знайдену на даний момент послідовність.
    - currentCount = 0 → підраховує поточну серію послідовних одиниць.
  2. Перебір рядка. Для кожного символу в рядку:
    - Якщо це '1', збільшуйте currentCount.
    - Якщо це '0', скидайте currentCount до 0 (оскільки серія перервана).
    Після кожного кроку оновлюйте maxCount = Math.max(maxCount, currentCount).
  3. Повертаємо результат:
    В кінці maxCount зберігатиме довжину найдовшої послідовної послідовності
    одиниць. Повертаємо maxCount.
*/
function getLongestRepeatingOnes(s) {
  // ініціалізація лічильників
  let maxCount = 0; // змінна для підрахунку найдовшої знайденої на даний момент послідовності
  let currentCount = 0; // підраховує поточну серію послідовних одиниць

  // ітеруємо по кожному символу в рядку
  for (let char of s) {
    if (char === "1") {
      // якщо це '1', продовжуємо поточну серію
      currentCount++; // збільшуємо currentCount на 1
      // оновлюємо maxCount, якщо поточна серія довша
      if (currentCount > maxCount) {
        maxCount = currentCount;
      }
    } else {
      // якщо це '0', серія перервана → скидаємо currentCount
      currentCount = 0;
    }
  }

  // повертаємо найдовшу знайдену на даний момент послідовність
  return maxCount;
}
