/*
  Ваш вчитель написав на дошці три додатні числа A, B, C. Потім він дає вам 
  завдання: виберіть одне з трьох чисел і замініть його його квадратом (X2),
  щоб при додаванні трьох чисел після заміни ви отримали максимально можливу суму.
  Напишіть функцію з назвою sum, яка має три натуральні числа A, B, C, задані
  на вході. Поверніть максимально можливу суму, замінивши одне число його квадратом.
  Вхідні дані: 1 5 5; Вихідні дані: 31
  Вхідні дані: 0 1 10; Вихідні дані: 101
*/
// Solution:
/* Алгоритм
  Вхідні дані: три натуральні числа 𝐴,𝐵,𝐶.
  Задача: замінити одне з них на його квадрат, щоб сума трьох чисел стала максимальною.
  Кроки: Обчислити три можливі суми:
    Якщо квадратуємо 𝐴: 𝐴*A+𝐵+𝐶
    Якщо квадратуємо 𝐵: 𝐴+𝐵*B+𝐶
    Якщо квадратуємо 𝐶: 𝐴+𝐵+𝐶*C
  Вибрати найбільшу з цих трьох сум.
  Повернути цю найбільшу суму.
*/
function sum(A, B, C) {
  const option1 = A * A + B + C;
  const option2 = A + B * B + C;
  const option3 = A + B + C * C;

  return Math.max(option1, option2, option3);
}
// Tests:
console.log(sum(1, 5, 5)); // 31
console.log(sum(0, 1, 10)); // 101

