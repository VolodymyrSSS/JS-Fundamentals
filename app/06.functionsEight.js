/*
  Можна просто перевіряти кожен символ і рахувати, скільки разів він
  зустрічається в рядку. Aле цей підхід є менш ефективний (O(n²)), бо
  для кожного символа ми знову проходимо рядок. Рішення:
*/
function singleChar2(s) {
  // проходимо по кожному символу
  for (let char of s) {
    // рахуємо кількість входжень
    const count = s.split("").filter((c) => c === char).length;
    // якщо символ зустрівся лише один раз
    if (count === 1) {
      return char;
    }
  }
}
