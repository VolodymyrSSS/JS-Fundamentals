/*
 Напишіть функцію isConstructable, яка отримує два рядки, s1 та s2, і повертає
 true, якщо s1 можна побудувати, використовуючи літери з s2, або false в іншому
 випадку. Приклад:
    Вхідні дані - "aab", "bcaa"
    Очікуваний вихідний дані - true, бо "bcaa" містить усі літери з "aab".
*/
// Solution:
/*
  1. Створюємо лічильник для символів у s2.
  2. Проходимо по кожному символу s1.
  - Якщо символ є в лічильнику і його кількість > 0 → зменшуємо лічильник.
  - Якщо символа немає або кількість = 0 → повертаємо false.
  3. Якщо всі символи пройшли перевірку → повертаємо true.
*/
function isConstructable1(s1, s2) {
  const count = {}; // створюємо об’єкт для підрахунку кількості символів у s2

  // проходимо по кожному символу s2
  for (let char of s2) {
    count[char] = (count[char] || 0) + 1; // збільшуємо лічильник для символа
  }

  // перевіряємо кожен символ з s1
  for (let char of s1) {
    // якщо символа немає або його кількість = 0
    if (!count[char]) {
      return false; // не можемо побудувати s1
    }
    count[char]--; // використовуємо одну копію символа
  }

  return true; // всі символи знайдені
}
