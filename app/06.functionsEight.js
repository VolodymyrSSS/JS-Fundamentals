/*
  Write a function named mergeSort that gets two sorted lists as input, merges
  them into one sorted list, and returns it.
  For Example:
    Input:
      [1, 4, 6, 8, 14, 23]
      [2, 3, 5, 7, 11, 18, 19, 20]
    Expected Output:
      [1, 2, 3, 4, 5, 6, 7, 8, 11, 14, 18, 19, 20, 23]
*/
// Solution via using a two‑pointer approach:
/*
  Algorithm:
  1. Create an empty array to hold the merged result.
  2. Initialize two pointers, one for each input array, starting at index 0.
  3. While both pointers are within the bounds of their respective arrays:
     a. Compare the elements at the two pointers.
     b. Push the smaller element to the merged array and move that pointer forward.
  4. If one of the arrays is exhausted, append the remaining elements from the other array.
  5. Return the merged array. 
*/
function mergeSort(a1, a2) {
  // створюємо масив для збереження об'єднаного результату
  const merged = [];

  // ініціалізуємо два показника для кожного масиву
  let i = 0; // показник для a1
  let j = 0; // показник для a2

  // ітеруємо по масивам, доки один з масивів не буде повністю пройдено
  while (i < a1.length && j < a2.length) {
    // порівнюємо поточні елементи з обох масивів
    // якщо a1[i] менше, додаємо його до merged
    if (a1[i] < a2[j]) {
      merged.push(a1[i]);
      i++; // збільшуємо показник для a1
    } else {
      // інакше, додаємо a2[j] до merged
      merged.push(a2[j]);
      j++; // збільшуємо показник для a2
    }
  }

  // якщо є залишкові елементи в a1, додаємо їх усі
  while (i < a1.length) {
    merged.push(a1[i]);
    i++;
  }

  // якщо є залишкові елементи в a2, додаємо їх усі
  while (j < a2.length) {
    merged.push(a2[j]);
    j++;
  }
  /*Особливість алгоритму з двома вказівниками полягає:
    Перший тип циклу: while (i < a1.length && j < a2.length) виконується доти, 
    доки в обох масивах залишилися елементи. Він порівнює поточний елемент a1 та
    a2, бере менший елемент і переміщує вказівник вперед. Це гарантує, що ми
    завжди вибираємо наступний найменший елемент, доки один з масивів не буде
    повністю використаний.
    Другий тип циклів: while (i < a1.length) та while (j < a2.length) визначає:
    як тільки один масив порожній, інший все ще може мати залишки елементів.
    Оскільки обидва масиви були відсортовані з самого початку, ці залишки вже
    знаходяться в відсортованому порядку. Ми просто додаємо їх безпосередньо
    до результату без подальших порівнянь.
  */

  // повертаємо повністю об'єднаний і відсортований масив
  return merged;
}
