/*
  Напишіть функцію з назвою longestPalindrome, яка знаходить найдовший 
  паліндромний підрядок у рядку.
  Паліндромний підрядок – це підрядок, який також є паліндромом.
  Функція повинна приймати рядок на вхід і повертати найдовший паліндромний
  підрядок. Якщо існує кілька паліндромних підрядків однакової довжини, функція
  повинна повертати перший, що з'являється в рядку.
*/
// Solution:
/*
  Iдея алгоритму (Expand Around Center)
  1. Кожен паліндром має «центр».
  2. Центр може бути:
    - один символ (непарна довжина),
    - aбо між двома символами (парна довжина).
  3. Для кожної позиції в рядку ми розширюємося вліво і вправо,
     поки символи збігаються.
  4. Запам’ятовуємо найдовший знайдений паліндром.
  Це дає час O(n²), але для практичних задач цього достатньо.
*/
function longestPalindrome(s) {
  if (s.length === 0) return "";

  let start = 0; // початок найдовшого паліндрома
  let maxLen = 1; // довжина найдовшого паліндрома

  // допоміжна функція для розширення навколо центру
  function expandAroundCenter(left, right) {
    while (left >= 0 && right < s.length && s[left] === s[right]) {
      left--;
      right++;
    }
    // після виходу з циклу межі вже вийшли за паліндром
    return [left + 1, right - 1];
  }

  for (let i = 0; i < s.length; i++) {
    // непарна довжина (центр у символі)
    let [l1, r1] = expandAroundCenter(i, i);
    if (r1 - l1 + 1 > maxLen) {
      start = l1;
      maxLen = r1 - l1 + 1;
    }

    // парна довжина (центр між символами)
    let [l2, r2] = expandAroundCenter(i, i + 1);
    if (r2 - l2 + 1 > maxLen) {
      start = l2;
      maxLen = r2 - l2 + 1;
    }
  }

  return s.substring(start, start + maxLen);
}
// Tests:
console.log(longestPalindrome("civic")); // civic
console.log(longestPalindrome("abc")); // a
console.log(longestPalindrome("abccdefg")); // cc
console.log(longestPalindrome("no palindromes here")); // ere

