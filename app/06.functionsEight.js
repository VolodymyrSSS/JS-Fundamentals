/*
  Напишіть функцію findPair, яка отримує масив цілих чисел arr та цільове 
  число k і повертає true, якщо в arr є пара цілих чисел, сума яких дорівнює
  k, інакше повертає false.  Приклад:
  Вхідні дані - arr = [1, 2, 3, 4], k = 6
  Очікуваний вихідний дані - true бо пара (2, 4), яка існує в arr, дорівнює
  k (це також єдина пара!).
  Примітка: arr не є відсортованим масивом.
*/
// Solution:
/*
  Це класична задача з двома сумами — нам потрібно перевірити, чи будь-які два
  числа в масиві дорівнюють k. Оскільки масив не відсортований, найефективнішим
  способом є використання множини Set (або хеш-карти Map) для відстеження
  доповнень у процесі сортування. Отже алгоритм рішення буде:
  Перебираємо кожне число в arr.
    1. Для кожного числа num обчислюємо needed = k - num;
    2. Якщо needed вже є в наборі, повертаємо true (ми знайшли пару).
    3. В іншому випадку додаємо num до набору та продовжуємо.
    4. Якщо до кінця пара не знайдена, повертаємо false.
  Це виконується за час O(n) та використовує O(n) додаткового простору.  
*/
function findPair1(arr, k) {
  const seen = new Set(); // створюємо множину для відстеження чисел, які вже зустрічалися

  // проходимо по кожному числу масиву
  for (let num of arr) {
    const needed = k - num; // обчислюємо число, яке потрібно для пари (щоб сума дорівнювала k)

    // перевіряємо, чи це потрібне число вже є в множині
    if (seen.has(needed)) {
      return true; // знайшли пару, яка дає суму k
    }
    seen.add(num); // додаємо поточне число в множину для подальших перевірок
  }

  return false; // якщо цикл завершився і пари не знайдено — повертаємо false
}
