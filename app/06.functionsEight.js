/*
  Напишіть функцію з назвою lcm (LCM - Least Common Multiple або НСК - найменше
  спільне кратне), якій задано два натуральні числа a та b з вхідних даних. 
  Поверніть їх НСК у блоці коду.
  Найменше спільне кратне (НСК) для двох цілих чисел a та b — це найменше додатне
  ціле число, яке безперервно ділиться як на a, так і на b.
  Вхідні дані: 2 3; Вихідні дані: 6
  Вхідні дані: 4 8; Вихідні дані: 8
*/
// Solution:
/* Алгоритм рішення:
  1.Прочитати два числа 𝑎 і 𝑏.
  2. Знайти їхній НСД (GCD).
    Це можна зробити через алгоритм Евкліда.
    Використати формулу: 𝐿𝐶𝑀(𝑎,𝑏)=(𝑎*𝑏)/𝐺𝐶𝐷(𝑎,𝑏)
  3. Повернути результат.
  
  При цьому GCD (Greatest Common Divisor) - або НСД (найбільший спільний дільник)
  двох чисел. Тобто найбільше число, яке ділить і 𝑎, і 𝑏 без остачі. Наприклад:
  𝐺𝐶𝐷(12,18)=6(бо 6 — найбільше число, яке ділить і 12, і 18).
  𝐺𝐶𝐷(8,20)=4.
  Iдея дуже проста: НСД двох чисел не змінюється, якщо більше число замінити на 
  остачу від ділення на менше. Повторюємо, доки остача не стане 0. Тоді друге 
  число — це і є НСД.

  Є важлива формула: 𝐿𝐶𝑀(𝑎,𝑏)⋅𝐺𝐶𝐷(𝑎,𝑏)=𝑎⋅𝑏
  Тобто рішенням буде: спочатку знаходимо GCD, а потім ділимо добуток на нього.
  Це найефективніший і найпоширеніший спосіб обчислення LCM.
*/
function lcm(a, b) {
  // Допоміжна функція для GCD за алгоритмом Евкліда
  function gcd(x, y) {
    // поки друге число не стало нулем
    while (y !== 0) {
      const temp = y; // запам’ятовуємо y
      y = x % y; // нове y = остача від ділення x на y
      x = temp; // x стає старим y
    }
    return x; // коли y = 0, x — це НСД
  }

  return (a * b) / gcd(a, b); // НСК - найменше спільне кратне
}
// Tests:
console.log(lcm(2, 3)); // 6
console.log(lcm(4, 8)); // 8

