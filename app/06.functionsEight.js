/*
  Напишіть функцію secondMost, яка отримує на вхід список цілих чисел та
  повертає друге за частотою повторюване число. Наприклад:
    Вхідні дані:
      [98, 72, 93, 72, 83, 98, 72, 44, 25, 53, 43, 98, 81, 98]
    Очікуваний результат:
      72
  Пояснення: число 72 повторюється в списку 3 рази, одразу після 98, яке повторюється
  4 рази. Тому 72 є друге за частотою повторюваності число.
*/
// Solution:
/* Алгоритм рішення:
  1. Підрахунок частоти повторюваності:
    Створити карту (об'єкт) для зберігання кількості разів, коли кожне ціле число
    з'являється у списку. Приклад: [98, 72, 93, 72] → {98:2, 72:2, 93:1}.
  2. Сортування за частотою:
    - Перетворити об'єкт на масив пар [число, кількість];
    - Сортуйте цей масив за кількістю у порядку спадання;
  3. Вибір другого за частотою:
    - Вибераємо число з індексом 1 (другий елемент після сортування).
  4. Повернення результату:
    - Якщо є другий за частотою елемент, поверніть його; інакше поверніть null або повідомлення про відсутність.
*/
function secondMost(a) {
  // створюємо об'єкт для підрахунку частоти повторюваностей
  const freq = {};

  // підраховуємо частоту кожного числа у масиві
  for (const num of a) {
    // якщо число вже існує, збільшити лічильник; інакше встановити значення на 1
    freq[num] = (freq[num] || 0) + 1;
  }

  // перетворюємо об'єкт на масив пар [число, кількість]
  const entries = Object.entries(freq);

  // сортуючи за кількістю у порядку спадання
  // кожна пара виглядає як ["number", count], тому a[1] це частота повторюваності в парі a,
  // b[1] — частота повторюваності в парі b.
  entries.sort((a, b) => b[1] - a[1]);
  // після сортування, масив пар має вид типу [["98", 4], ["72", 3], ["93", 1], ...]
  // де entries[0] — це число з найбільшою частотою повторюваності, entries[1] — друге за частотою.

  // вибираєм друге за частотою повторюваності пару в якій беремо значення числа (entries[1][0])
  // яке перетворюємо на числоза допомогою Number()
  return entries.length >= 2 ? Number(entries[1][0]) : null;
}
