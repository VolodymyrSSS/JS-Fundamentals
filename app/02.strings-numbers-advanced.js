// Функція для обчислення суми цифр числа
function sumOfDigits(num) {
  let sum = 0; // змінна для накопичення суми
  let str = num.toString(); // перетворюємо число у рядок
  for (let i = 0; i < str.length; i++) {
    // перебираємо кожен символ
    sum += Number(str[i]); // додаємо цифру до суми попередньо перетворивши її на число
  }
  return sum; // повертаємо суму цифр
}

