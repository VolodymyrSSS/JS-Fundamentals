/* 1. Якщо довжини чисел різні → вони точно не анаграми.
   2. Інакше для кожної цифри з першого числа перевіряємо, чи вона є в другому.
   3. Щоб уникнути повторів, можна видаляти знайдену цифру з другого числа (щоб 
      одна цифра не рахувалась двічі).
   4. Якщо всі цифри знайшлися → це анаграма.
*/

