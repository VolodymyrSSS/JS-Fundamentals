/*
  Ваш друг хоче спілкуватися з вами за допомогою зашифрованих повідомлень. Щоб зашифрувати
  повідомлення, вам потрібно знати правила, як це зробити. Коли ви хочете надіслати
  повідомлення, ви перевертаєте його, а на парних індексах ви ставите символ X, який буде
  вказаний. Примітка: Перший індекс дорівнює 0.
  Напишіть програму, яка зчитує символ X, а потім повідомлення зі стандартного вводу та
  виводить потрібне шифрування.
    Вхід:
      #
      075385
    Вихід:
      #8#5#0
*/
// Solution:
/* Алгоритм рішення:
  1. Зчитати символ X (який буде вставлятися на парні індекси).
  2. Зчитати повідомлення як рядок.
  3. Перевернути повідомлення (reverse).
  4. Створити новий рядок:
     - Якщо індекс парний → вставити символ X.
     - Якщо індекс непарний → вставити відповідний символ із перевернутого повідомлення.
  5. Вивести результат.
*/
// Підключаємо модуль fs для читання вводу
// const fs = require("fs");
// Зчитуємо ввід і розділяємо по рядках
// const input = fs.readFileSync(0, "utf8").trim().split("\n"); aбо

const input13 = ["#", "075385"]; // вхідні дані

const X13 = input13[0].trim(); // Перший рядок — символ X
const message = input13[1].trim(); // Другий рядок — повідомлення

// перевертаємо повідомлення
const reversed = message.split("").reverse().join("");

// будуємо зашифрований рядок
let encrypted = "";
for (let i = 0; i < reversed.length; i++) {
  if (i % 2 === 0) {
    encrypted += X13; // на парних індексах ставимо X
  } else {
    encrypted += reversed[i]; // на непарних індексах ставимо символ
  }
}

